WORLD = (
    "Before heaven and earth there was only **Hundun (混沌)**, endless chaos. Within it a Will was born: the **Great Dao**. "
    "The Dao gave birth to three thousand **Chaos Demon Gods**. The strongest, **Pangu (盘古)**, slew all the others and split the chaos in two. "
    "His body and blood became the primordial world, **Honghuang (洪荒)**.\n\n"
    "The ages of Honghuang were written in calamity: the wars of the old clans, the Investiture of the Gods, the long pilgrimage to the west. "
    "When the last great calamity ended and the Sages withdrew, the world could no longer carry the weight of the Dao. It broke. "
    "This was the **Shattering**. Honghuang split into thousands of **Lower Worlds**, a ring of **Middle Worlds**, and a single **Immortal World** above them all.\n\n"
    "What fell last, and lowest, was **Canhuang (残荒)**, a world made of nothing but the remnants of Honghuang itself: Pangu's bones as mountains, "
    "his blood in the rivers and the old Dao in the soil. Qi is thin here. Spiritual roots are shards of Pangu's will carried in blood, and the great sects "
    "keep them alive: **Wanjian Pavilion (万剑阁)** of the sword, **Xuanwu Hall (玄武殿)** of the body, **Danding Valley (丹鼎谷)** of alchemy and "
    "**Tianji Pavilion (天机阁)** of formations.\n\n"
    "Many peoples live in Canhuang: **humans**, **demons** who grasped the Dao, **beastkin** of the wild, **spirits** born of rock, tree and water, "
    "**witches** of Pangu's blood and their half-blood **witch-humans**, **ghosts** from the Underworld, the fallen blood of **immortals**, and the **demonic** heirs of the Chaos Demon Gods.\n\n"
    "Beneath the four great pavilions the world is held together by **clans**: great families of cultivators who share blood, oaths and one banner. "
    "Most of them have fallen. The few that remain are called the **fallen clans**, and every cultivator in Canhuang belongs to one, or is looking for one.\n\n"
    "The way to the Immortal World is sealed behind the **Heaven Gate**, and the Shattering never truly stopped."
)

ABYSS = (
    "Every cultivator who died in the great calamities left something behind: their last thought, their last grief, their last hatred. "
    "That resentment gathers in the thin places of the world and takes a shape. These are the **Abyssal Beasts (渊兽)**. "
    "They are not born. They are what is left of the mighty, and they remember how to hate.\n\n"
    "They roam the wilds of Canhuang and spill out of rifts. The strongest of them, the **Abyssal Lords**, still carry the shape of the cultivators they once were."
)

CLANS = (
    "A clan is a family bigger than blood. The **Young Master** (the clan head) carries the banner, **Elders** guard the hall and every **Member** carries the name. "
    "A fallen clan has lost its mountain, but not its banner. Raise the banner again, build the hall with coin and oath, and the world will remember it."
)

RIFTS = (
    "When a lower world breaks from Honghuang, it leaves a scar in the sky. These scars are **rifts**. Each leads to one lower world, a place that was whole once and is only ruins now. "
    "Inside are beasts, forgotten halls, wandering ghosts and fortune. Nobody has ever found the same lower world twice."
)
